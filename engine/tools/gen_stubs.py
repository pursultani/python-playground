"""Generate the editor stub `engine/typings/__builtins__.pyi` from the source of `core`.

Pyright and Pylance read `<stubPath>/__builtins__.pyi` and add its names to the built-ins, so
students get autocomplete, hover help and typo checks without ever writing an import.

    python engine/tools/gen_stubs.py            write the stub
    python engine/tools/gen_stubs.py --check    fail if the committed stub is out of date
"""

from __future__ import annotations

import argparse
import ast
import difflib
import re
import sys
from pathlib import Path
from typing import Any

import griffe

ROOT = Path(__file__).resolve().parents[2]
LIB = ROOT / "engine" / "lib"
STUB = ROOT / "engine" / "typings" / "__builtins__.pyi"
LINE_LENGTH = 100

HEADER = """\
# Generated by engine/tools/gen_stubs.py from engine/lib/core. Do not edit.
# Regenerate with `make stubs`.
"""

# griffe's object tree is loosely typed (members may be aliases), so keep annotations simple.
Member = Any


def _is_prop(member: Member) -> bool:
    value = getattr(member, "value", None)
    function = getattr(value, "function", None)
    return isinstance(member, griffe.Attribute) and getattr(function, "name", "") == "prop"


def _is_method(member: Member) -> bool:
    return isinstance(member, griffe.Function) and not member.name.startswith("_")


def _chain(cls: griffe.Class) -> list[griffe.Class]:
    return [cls, *cls.mro()]


def _excluded(cls: griffe.Class) -> list[str]:
    member = cls.members.get("_excluded")
    value = getattr(member, "value", None)
    return list(ast.literal_eval(str(value))) if value is not None else []


def _effective(cls: griffe.Class) -> dict[str, Member]:
    """Properties and methods of `cls`, bases flattened, `_excluded` honoured (like the runtime)."""
    found: dict[str, Member] = {}
    for base in reversed(_chain(cls)):
        for name, member in base.members.items():
            if name.startswith("_"):
                continue
            if _is_prop(member) or _is_method(member):
                found[name] = member
        for name in _excluded(base):
            found.pop(name, None)
    return found


def _init_of(cls: griffe.Class) -> griffe.Function | None:
    for base in _chain(cls):
        init = base.members.get("__init__")
        if isinstance(init, griffe.Function):
            return init
    return None


def _literal(default: str) -> str:
    """Write a default value the way `ruff format` does (double quotes)."""
    try:
        value = ast.literal_eval(default)
    except (ValueError, SyntaxError):
        return default
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    return default


def _param(param: griffe.Parameter) -> str:
    text = f"*{param.name}" if param.kind is griffe.ParameterKind.var_positional else param.name
    if param.kind is griffe.ParameterKind.var_keyword:
        text = f"**{param.name}"
    if param.annotation is not None:
        text += f": {param.annotation}"
    if param.default is not None:
        sep = " = " if param.annotation is not None else "="
        text += f"{sep}{_literal(str(param.default))}"
    return text


def _signature(func: griffe.Function, indent: str, keyword: str = "def") -> list[str]:
    parts: list[str] = []
    previous = None
    for param in func.parameters:
        kind = param.kind
        if previous is griffe.ParameterKind.positional_only and (
            kind is not griffe.ParameterKind.positional_only
        ):
            parts.append("/")
        if kind is griffe.ParameterKind.keyword_only and previous not in (
            griffe.ParameterKind.keyword_only,
            griffe.ParameterKind.var_positional,
        ):
            parts.append("*")
        parts.append(_param(param))
        previous = kind
    returns = f" -> {func.returns}" if func.returns is not None else ""
    one_line = f"{indent}{keyword} {func.name}({', '.join(parts)}){returns}:"
    if len(one_line) <= LINE_LENGTH:
        return [one_line]
    inner = indent + "    "
    return [
        f"{indent}{keyword} {func.name}(",
        *[f"{inner}{p}," for p in parts],
        f"{indent}){returns}:",
    ]


def _docstring(member: Member, indent: str) -> list[str]:
    doc = member.docstring
    if doc is None or not doc.value.strip():
        return []
    text = doc.value.strip().replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    lines = text.split("\n")
    if len(lines) == 1 and not text.endswith('"'):
        return [f'{indent}"""{text}"""']
    body = [f"{indent}{line}" if line else "" for line in lines[1:]]
    return [f'{indent}"""{lines[0]}', *body, f'{indent}"""']


def _prop_lines(name: str, member: Member) -> list[str]:
    annotation = str(member.annotation) if member.annotation is not None else "Any"
    return [f"    {name}: {annotation}", *_docstring(member, "    ")]


def _function_lines(func: griffe.Function, indent: str) -> list[str]:
    return [*_signature(func, indent), *(_docstring(func, indent + "    ") or [f"{indent}    ..."])]


class _Stub:
    def __init__(self) -> None:
        self.pkg = griffe.load("core", search_paths=[str(LIB)], docstring_parser=None)
        self.exports = [str(name) for name in self.pkg.exports or []]
        members: Any = self.pkg.members
        self.targets = {name: members[name].final_target for name in self.exports}
        self.classes = {n: t for n, t in self.targets.items() if isinstance(t, griffe.Class)}
        self.functions = {n: t for n, t in self.targets.items() if isinstance(t, griffe.Function)}
        self.by_path = {cls.path: name for name, cls in self.classes.items()}
        self.bases = {name: self._exported_bases(cls) for name, cls in self.classes.items()}
        self.effective = {name: _effective(cls) for name, cls in self.classes.items()}
        self._visible: dict[str, dict[str, Member]] = {}

    def _exported_bases(self, cls: Any) -> list[str]:
        found: list[str] = []
        for base in cls.resolved_bases:
            if base.path in self.by_path:
                found.append(self.by_path[base.path])
            else:
                found.extend(self._exported_bases(base))
        return found

    def _descendants(self, name: str) -> list[str]:
        return [other for other in self.classes if other != name and name in self._ancestors(other)]

    def _ancestors(self, name: str) -> set[str]:
        found: set[str] = set()
        for base in self.bases[name]:
            found |= {base} | self._ancestors(base)
        return found

    def visible(self, name: str) -> dict[str, Member]:
        """What the stub class `name` offers, including what it inherits from stub bases.

        A base only offers members that every exported subclass also has, so a member that a
        subclass removes (`Line.rotation`) is declared per subclass, never inherited.
        """
        if name not in self._visible:
            members = dict(self.effective[name])
            for other in self._descendants(name):
                members = {k: v for k, v in members.items() if k in self.effective[other]}
            self._visible[name] = members
        return self._visible[name]

    def provided(self, name: str) -> dict[str, Member]:
        found: dict[str, Member] = {}
        for base in self.bases[name]:
            found.update(self.visible(base))
        return found

    def own_members(self, name: str) -> dict[str, Member]:
        inherited = self.provided(name)
        own = {}
        for key, member in self.visible(name).items():
            if key in inherited and inherited[key].path == member.path:
                continue
            own[key] = member
        return own

    def order(self) -> list[str]:
        placed: list[str] = []

        def place(name: str) -> None:
            if name in placed:
                return
            for base in self.bases[name]:
                place(base)
            placed.append(name)

        for name in self.classes:
            place(name)
        return placed

    def class_lines(self, name: str) -> list[str]:
        cls = self.classes[name]
        bases = self.bases[name]
        head = f"class {name}({', '.join(bases)}):" if bases else f"class {name}:"
        doc = _docstring(cls, "    ")
        lines = [head, *doc, *([""] if doc else [])]
        own = self.own_members(name)
        init = _init_of(cls)
        provided_init = {
            init_of.path for b in bases if (init_of := _init_of(self.classes[b])) is not None
        }
        order = [p.name for p in init.parameters] if init is not None else []
        props = {k: m for k, m in own.items() if _is_prop(m)}
        methods = {k: m for k, m in own.items() if _is_method(m)}
        for key in sorted(props, key=lambda k: order.index(k) if k in order else len(order)):
            lines += _prop_lines(key, props[key])
        if init is not None and init.path not in provided_init:
            lines += _function_lines(init, "    ")
        for key in methods:
            lines += _function_lines(methods[key], "    ")
        if len(lines) == 1:
            lines.append("    ...")
        while lines[-1] == "":
            lines.pop()
        return lines

    def render(self) -> str:
        blocks = ["\n".join(self.class_lines(name)) for name in self.order()]
        for func in self.functions.values():
            blocks.append("\n".join(_function_lines(func, "")))
        body = "\n\n".join(blocks) + "\n"
        imports = []
        if re.search(r"\bCallable\b", body):
            imports.append("from collections.abc import Callable")
        if re.search(r"\bAny\b", body):
            imports.append("from typing import Any")
        top = HEADER + ("\n" + "\n".join(imports) + "\n" if imports else "")
        return f"{top}\n{body}"


def generate() -> str:
    """Return the text of `__builtins__.pyi` for the current source of `core`."""
    return _Stub().render()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate engine/typings/__builtins__.pyi")
    parser.add_argument("--check", action="store_true", help="fail if the stub is out of date")
    args = parser.parse_args(argv)
    text = generate()
    current = STUB.read_text() if STUB.exists() else ""
    if args.check:
        if current == text:
            print("The editor stub is up to date.")
            return 0
        diff = difflib.unified_diff(
            current.splitlines(), text.splitlines(), "committed", "generated", lineterm=""
        )
        print("\n".join(list(diff)[:60]))
        print("\nThe editor stub is out of date. Run `make stubs` and commit the result.")
        return 1
    STUB.parent.mkdir(parents=True, exist_ok=True)
    STUB.write_text(text)
    print(f"Wrote {STUB.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
